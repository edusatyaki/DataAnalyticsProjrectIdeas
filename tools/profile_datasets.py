"""Write DATA_PROFILE.md (column-by-column profile) into every project's folder.

Run from the repo root:  python tools/profile_datasets.py
"""
import gzip
from pathlib import Path
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent


def load(path):
    # CPI files start with a '# source' line; don't use comment="#" since product names contain '#'
    opener = gzip.open if path.suffix == ".gz" else open
    with opener(path, "rb") as fh:
        skip = 1 if fh.read(1) == b"#" else 0
    try:
        df = pd.read_csv(path, skiprows=skip, low_memory=False)
    except UnicodeDecodeError:  # Superstore ships as Windows-1252
        df = pd.read_csv(path, skiprows=skip, low_memory=False, encoding="cp1252")
    return {path.name: df}


def fmt(v):
    s = str(v).replace("|", "/").replace("\n", " ")
    return s if len(s) <= 40 else s[:37] + "..."


def profile(name, df):
    lines = [f"### `{name}`", "", f"**{len(df):,} rows × {df.shape[1]} columns**", ""]
    dates = [c for c in df.columns if pd.to_datetime(pd.Series([c]), format="%m/%d/%y", errors="coerce").notna().all()]
    if len(dates) > 20:  # wide time series: one column per day
        lines.append(f"Wide format: **{len(dates):,} daily date columns** from `{dates[0]}` to `{dates[-1]}` "
                     f"(cumulative counts, last-day total {df[dates[-1]].sum():,.0f}). Melt to long format before analysis.")
        lines.append("")
        df = df.drop(columns=dates)
    lines += [
"| # | Column | Type | Non-null | Missing % | Unique | Min / Top value | Max / Sample values |",
             "|---|---|---|---|---|---|---|---|"]
    for i, c in enumerate(df.columns, 1):
        s = df[c]
        miss = s.isna().mean() * 100
        nun = s.nunique(dropna=True)
        if pd.api.types.is_numeric_dtype(s) and s.notna().any():
            lo, hi = fmt(round(s.min(), 3)), fmt(round(s.max(), 3))
        elif s.notna().any():
            vc = s.astype(str).value_counts()
            lo = f"{fmt(vc.index[0])} ({vc.iloc[0]:,})"
            hi = ", ".join(fmt(x) for x in vc.index[:4]) if nun <= 12 else ", ".join(fmt(x) for x in s.dropna().astype(str).unique()[:3])
        else:
            lo = hi = "—"
        lines.append(f"| {i} | `{fmt(c)}` | {s.dtype} | {s.notna().sum():,} | {miss:.1f} | {nun:,} | {lo} | {hi} |")
    dup = df.duplicated().sum()
    lines += ["", f"Exact duplicate rows: **{dup:,}**", ""]
    return "\n".join(lines)


for proj in sorted(p for p in ROOT.iterdir() if p.is_dir() and p.name[:2].isdigit()):
    files = sorted(f for f in (proj / "data").rglob("*") if f.suffix in {".csv", ".gz"})
    if not files:
        continue
    out = [f"# Data profile — {proj.name.replace('_', ' ')}", "",
           "Generated by `tools/profile_datasets.py`. Numeric columns show min/max; text columns show the most frequent value and a few samples.", ""]
    for f in files:
        for name, df in load(f).items():
            name = f.relative_to(proj / "data").as_posix()  # keeps the subfolder, e.g. 01's two sets
            out.append(profile(name, df))
            print(f"{proj.name}: {name} {df.shape}")
    (proj / "DATA_PROFILE.md").write_text("\n".join(out))
